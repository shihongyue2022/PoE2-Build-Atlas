import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
try {
  await page.route('**/api/workbench/affix-reference', route => route.fulfill({ status: 503, json: { ok: false } }));
  await page.route('**/api/workbench/pob/builds', route => route.fulfill({ json: { ok: true, installed: false, builds: [] } }));
  await page.route('**/api/workbench/trade-log*', route => route.fulfill({ json: { ok: true, found: false, events: [] } }));
  await page.route('**/api/workbench/craft-exchange?*', route => route.fulfill({ json: { ok: true, exchange: { league: new URL(route.request().url()).searchParams.get('league'), source: 'poe.ninja', asOf: '2026-10-24T00:00:00Z', rates: { exalted: 1, divine: 100, chaos: 5 } } } }));
  await page.goto(process.env.WORKBENCH_URL ?? 'http://127.0.0.1:5175/?companion=1');
  await page.getByRole('button', { name: '制作策略', exact: true }).click();
  const panel = page.getByRole('region', { name: '成品目标制作规划' });
  await panel.getByRole('button', { name: '60% 品质裂痕戒指' }).click();
  const actual = panel.getByRole('region', { name: '实际底装核对' });
  const raw = await page.evaluate(async () => (await import('/src/workbench/fixtures/breachRing.ts')).FRACTURED_COLD_BREACH_RING_SAMPLE);
  await actual.getByRole('textbox').fill(raw); await actual.getByRole('button', { name: '导入底装', exact: true }).click();
  const comparison = actual.getByRole('region', { name: '底装与目标词缀对比' });
  await expect(comparison).toBeVisible(); await expect(comparison.getByLabel('含破裂的目标槽位')).toContainText('前缀 4/3');
  const goals = comparison.getByRole('region', { name: '本次制作目标微调' });
  await expect(comparison.getByRole('region', { name: '实际底装词缀校正' }).getByRole('group', { name: /^底装词缀/ })).toHaveCount(6);
  await actual.getByRole('button', { name: '核对底装', exact: true }).click();
  await expect(actual.getByRole('alert')).toContainText('4 条前缀');
  await goals.getByRole('row', { name: '目标条目 3', exact: true }).getByRole('checkbox').uncheck();
  await expect(comparison.getByLabel('含破裂的目标槽位')).toContainText('前缀 3/3');
  await actual.getByRole('button', { name: '核对底装', exact: true }).click();
  await expect(panel.getByRole('button', { name: '生成制作手顺', exact: true })).toBeEnabled();
  const currentSelect = comparison.getByRole('combobox', { name: '底装阶层校正：1' });
  const dimensions = await currentSelect.evaluate(element => {
    const style = getComputedStyle(element);
    const line = parseFloat(style.lineHeight);
    return { available: element.clientHeight - parseFloat(style.paddingTop) - parseFloat(style.paddingBottom), line: Number.isFinite(line) ? line : parseFloat(style.fontSize) * 1.2 };
  });
  assert(dimensions.available >= dimensions.line, `current-affix selectors must not clip their text: ${JSON.stringify(dimensions)}`);
  await mkdir('artifacts/workbench', { recursive: true });
  await comparison.screenshot({ path: 'artifacts/workbench/craft-base-target-comparison.png' });
  const materialLabel = await page.evaluate(async () => (await import('/src/workbench/craftBlueprint.ts')).blueprintMaterialLabel('Perfect Exalted Orb'));
  await panel.getByRole('combobox', { name: '补记其他耗材' }).selectOption('Perfect Exalted Orb');
  const material = page.getByRole('button', { name: `使用材料：${materialLabel}`, exact: true });
  await material.locator('img').hover();
  const tooltip = page.getByRole('tooltip');
  await expect(tooltip).toContainText('為一件稀有物品新增一項隨機詞綴');
  await expect(tooltip).toContainText('最小詞綴等級: 50');
  await expect(tooltip).toContainText('右鍵點擊');
  const bounds = await tooltip.boundingBox(); assert(bounds && bounds.x >= 0 && bounds.x + bounds.width <= 1600 && bounds.y + bounds.height <= 1000);
  await expect(material).toHaveAttribute('aria-pressed', 'true');
  const source = await tooltip.getByRole('link').getAttribute('href'); assert.equal(source, 'https://poe2db.tw/tw/Perfect_Exalted_Orb');
  await page.screenshot({ path: 'artifacts/workbench/craft-native-currency-tooltip.png' });
  await page.keyboard.press('Escape'); await expect(tooltip).toHaveCount(0);
  await material.focus(); await expect(tooltip).toBeVisible(); await page.keyboard.press('Escape');
  await expect(material).toHaveAttribute('aria-pressed', 'true');
  await page.setViewportSize({ width: 390, height: 844 });
  await comparison.screenshot({ path: 'artifacts/workbench/craft-base-target-comparison-mobile.png' });
  await material.locator('img').hover(); await expect(tooltip).toBeVisible();
  const mobile = await tooltip.boundingBox(); assert(mobile && mobile.x >= 0 && mobile.x + mobile.width <= 390 && mobile.y + mobile.height <= 844);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'artifacts/workbench/craft-native-currency-tooltip-mobile.png' });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '自由模拟', exact: true }).click();
  await page.getByRole('button', { name: '粘贴游戏物品', exact: true }).click();
  const flask = await page.evaluate(async () => (await import('/src/workbench/fixtures/fullGear.ts')).MANA_FLASK_SAMPLE);
  await page.getByRole('textbox', { name: '游戏物品文本' }).fill(flask);
  await page.getByRole('button', { name: /识别并导入/ }).click();
  await expect(page.getByRole('region', { name: '全物品查价' })).toContainText('魔力药剂');
  await expect(page.getByText(/首版仅支持|第一版只支持/)).toHaveCount(0);
  assert.deepEqual(errors, []);
  console.log('PASS native material hover/focus/escape, exact tier text, viewport bounds, actual-base comparison, fracture protection and mana-flask direct import.');
} finally { await browser.close(); }
